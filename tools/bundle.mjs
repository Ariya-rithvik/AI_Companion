/**
 * Bundle the console into single self-contained HTML files.
 *
 *   dist/backstage-demo.html      full document — double-click to run offline
 *   dist/backstage-artifact.html  body-only — for hosts that supply the skeleton
 *
 * The app is four ES modules. To inline them without a bundler we strip the
 * `import` lines and the `export` keywords, concatenate in dependency order,
 * and rebuild the one namespace object app.js actually uses (`E.*` for the
 * kernel) from the export names found in the source. Named imports from
 * surfaces.mjs and library.mjs become plain top-level consts, so app.js keeps
 * working untouched.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

const exportNames = src =>
  [...src.matchAll(/^export\s+(?:const|let|function)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1]);

/** Strip module syntax so the source can live inside one <script type="module">. */
const flatten = src => src.replace(/^import[\s\S]*?from\s+'[^']+';\s*$/gm, '').replace(/^export\s+/gm, '');

const engine = ['engine/surfaces.mjs', 'engine/core.mjs', 'engine/library.mjs'];
const sources = engine.map(f => ({ f, src: read(f), names: exportNames(read(f)) }));
for (const m of sources) {
  if (!m.names.length) throw new Error('no exports found in ' + m.f + ' — bundling would silently break');
}

const coreNames = sources.find(m => m.f.endsWith('core.mjs')).names;

const appSrc = read('web/app.js');
const cssSrc = read('web/style.css');
const htmlSrc = read('web/index.html');

const inlined = [
  sources.map(m => '/* ── ' + m.f + ' ── */\n' + flatten(m.src)).join('\n'),
  '/* ── kernel namespace, as app.js imports it ── */',
  'const E = { ' + coreNames.join(', ') + ' };',
].join('\n');

const app = appSrc.replace(/^import[\s\S]*?from\s+'[^']+';\s*$/gm, '');
if (app === appSrc) throw new Error('no import statements found in app.js — check the bundler regex');

/* ── assemble ────────────────────────────────────────────────────────────── */

const body = htmlSrc
  .replace(/^[\s\S]*?<body>\n?/, '')
  .replace(/<script type="module"[\s\S]*$/, '')
  .replace(/<\/body>[\s\S]*$/, '')
  .trimEnd();

const parts = [
  '<!-- Backstage · generated by tools/bundle.mjs · do not edit, edit web/ instead -->',
  '<title>Backstage</title>',
  '<style>\n' + cssSrc + '\n</style>',
  body,
  '<script type="module">\n' + inlined + '\n' + app + '\n<\/script>',
].join('\n');

fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'dist/backstage-artifact.html'), parts + '\n');
fs.writeFileSync(
  path.join(ROOT, 'dist/backstage-demo.html'),
  '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
  + '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
  + parts + '\n</body>\n</html>\n'
);

const kb = f => (fs.statSync(path.join(ROOT, f)).size / 1024).toFixed(0) + ' KB';
console.log('  dist/backstage-demo.html      ' + kb('dist/backstage-demo.html') + '   (standalone document)');
console.log('  dist/backstage-artifact.html  ' + kb('dist/backstage-artifact.html') + '   (body only)');
console.log('  inlined ' + sources.map(m => path.basename(m.f) + ':' + m.names.length).join('  '));
